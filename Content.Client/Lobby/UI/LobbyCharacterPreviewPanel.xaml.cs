namespace Content.Client.Lobby.UI;

/// <summary>
/// DarkestHour: «личное дело» персонажа в лобби (план осады п. 23, решения автора 2026-11-20). Персонаж показан в
/// снаряжении должности с высоким приоритетом (как раньше, <see cref="ProfileEditorControls.ProfilePreviewSpriteView"/>),
/// спереди и сбоку; стрелки листают сохранённых персонажей (<see cref="OnCycle"/> — их обрабатывает
/// <see cref="LobbyUIController"/>).
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class LobbyCharacterPreviewPanel : Control
{
    [Dependency] private IPrototypeManager _proto = default!;
    [Dependency] private JobRequirementsManager _jobRequirements = default!;
    [Dependency] private IPlayerManager _player = default!;

    private const string EmpireSide = "dh-jobs-side-empire";
    private const string RepublicSide = "dh-jobs-side-republic";

    public Button CharacterSetupButton => CharacterSetup;

    /// <summary>Нажата стрелка: −1 — предыдущий персонаж, +1 — следующий.</summary>
    public event Action<int>? OnCycle;

    public LobbyCharacterPreviewPanel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        DHFonts.RegisterTerminal(this);

        PrevButton.OnPressed += _ => OnCycle?.Invoke(-1);
        NextButton.OnPressed += _ => OnCycle?.Invoke(1);
    }

    public void SetLoaded(bool value)
    {
        Loaded.Visible = value;
        Unloaded.Visible = !value;
    }

    public void SetSummaryText(string value)
    {
        Summary.Text = value;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        Footer.Text = Loc.GetString("dh-lobby-file-footer", ("players", _player.PlayerCount));
    }

    /// <summary>Заполнить личное дело: персонаж <paramref name="slot"/> (номер <paramref name="position"/> из
    /// <paramref name="count"/>).</summary>
    public void SetProfile(HumanoidCharacterProfile? profile, int slot, int position, int count)
    {
        SidePreview.SetEntity(ProfilePreviewSpriteView.PreviewDummy);
        PrevButton.Disabled = NextButton.Disabled = count < 2;
        SlotLabel.Text = Loc.GetString("dh-lobby-file-slot", ("index", position + 1), ("count", count));
        FileNumber.Text = Loc.GetString("dh-lobby-file-number", ("slot", slot + 1));

        if (profile == null)
        {
            NameValue.Text = AgeValue.Text = BirthplaceValue.Text = EmpireValue.Text = RepublicValue.Text =
                SquadsValue.Text = string.Empty;
            return;
        }

        NameValue.Text = profile.Name;
        AgeValue.Text = profile.Age.ToString();
        BirthplaceValue.Text = profile.DHDetails.Birthplace is { } birthplace &&
                               _proto.TryIndex(birthplace, out var place)
            ? Loc.GetString(place.Name)
            : Loc.GetString("dh-lobby-file-unknown");
        EmpireValue.Text = BestJob(profile, EmpireSide);
        RepublicValue.Text = BestJob(profile, RepublicSide);
        SquadsValue.Text = Loc.GetString("dh-lobby-file-squads-value",
            ("empire", SquadName(profile.DHDetails.EmpireSquad)),
            ("republic", SquadName(profile.DHDetails.RepublicSquad)));

        var hours = (int) _jobRequirements.FetchOverallPlaytime().TotalHours;
        PlaytimeValue.Text = Loc.GetString("dh-lobby-file-hours", ("hours", hours));
    }

    /// <summary>Должность стороны с самым высоким приоритетом: «Стрелок десанта · высокий».</summary>
    private string BestJob(HumanoidCharacterProfile profile, string side)
    {
        var sideJobs = new HashSet<ProtoId<JobPrototype>>();
        foreach (var department in _proto.EnumeratePrototypes<DepartmentPrototype>())
        {
            if (department.DHSide?.Id == side)
                sideJobs.UnionWith(department.Roles);
        }

        var best = profile.JobPriorities
            .Where(p => p.Value != JobPriority.Never && sideJobs.Contains(p.Key))
            .OrderByDescending(p => p.Value)
            .Select(p => (Job: p.Key, Priority: p.Value))
            .FirstOrDefault();

        if (string.IsNullOrEmpty(best.Job.Id) || !_proto.TryIndex(best.Job, out var job))
            return Loc.GetString("dh-lobby-file-no-job");

        return Loc.GetString("dh-lobby-file-job", ("job", job.LocalizedName),
            ("priority", Loc.GetString(best.Priority switch
            {
                JobPriority.High => "dh-lobby-file-priority-high",
                JobPriority.Medium => "dh-lobby-file-priority-medium",
                _ => "dh-lobby-file-priority-low",
            })));
    }

    private string SquadName(string? squad)
    {
        return squad != null && _proto.TryIndex<DHSquadPrototype>(squad, out var proto)
            ? Loc.GetString(proto.Name)
            : Loc.GetString("dh-lobby-file-squad-any");
    }
}
