def glyph_mask(img):
    """Пиксели знака: отличаются от фона своей строки (берём пиксель у левого края внутри рамки)."""
    w, h = img.size
    px = img.load()
    mask = set()
    for y in range(h):
        ref = px[5, y]
        ref2 = px[w - 6, y]
        for x in range(6, w - 6):
            p = px[x, y]
            if p != ref and p != ref2 and abs(sum(p[:3]) - sum(ref[:3])) > 30:
                mask.add((x, y))
    return mask


def build(theme):
    slots = os.path.join(IFACE, theme, 'Slots')
    src = os.path.join(slots, 'uniform.png')
    if not os.path.exists(src):
        return False
    base = Image.open(src).convert('RGBA')
    if base.size != (32, 32):
        return False
    mask = glyph_mask(base)
    if not mask:
        return False
    px = base.load()
    colors = Counter(px[x, y] for x, y in mask)
    glyph = colors.most_common(1)[0][0]
    dark = tuple(int(c * 0.6) for c in glyph[:3]) + (glyph[3],)

    background = base.copy()
    bp = background.load()
    for x, y in mask:
        bp[x, y] = px[5, y]

    for name, art in (('arms', ARMS), ('legs', LEGS)):
        out = background.copy()
        op = out.load()
        rows = [r for r in art.strip('\n').split('\n')]
        for y, row in enumerate(rows):
            for x, ch in enumerate(row):
                if ch == '#':
                    op[x, y] = glyph
                elif ch == '+':
                    op[x, y] = dark
        out.save(os.path.join(slots, name + '.png'))
    return True


def main():
    for theme in sorted(os.listdir(IFACE)):
        if os.path.isdir(os.path.join(IFACE, theme, 'Slots')):
            print(theme, 'ok' if build(theme) else 'skipped')


if __name__ == '__main__':
    main()
