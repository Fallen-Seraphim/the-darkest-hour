import json as _json
_QUOTE = re.compile(r'^(\s*(?:name|description): )(.*)$')
def _q(l):
    m = _QUOTE.match(l)
    if not m or m.group(2).startswith('"'):
        return l
    return m.group(1) + _json.dumps(m.group(2), ensure_ascii=False)
def lines(*ls): return '\n'.join(_q(l) for l in ls) + '\n'

