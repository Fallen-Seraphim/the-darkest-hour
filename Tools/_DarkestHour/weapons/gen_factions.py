# ============================================================================= generation
def blocks(text):
    parts = re.split(r'(?m)^(?=- type: )', text)
    return parts[0], parts[1:]


def post_ammo(text):
    head, bl = blocks(text)
    out = []
    for b in bl:
        m = re.search(r'(?m)^  id: (DHBullet(\S+))$', b)
        if m and '  - type: Projectile' in b:
            bid = m.group(1)
            t = next(t for t in sorted(PEN_CLASS, key=len, reverse=True) if bid.endswith(t))
            pc = PEN_CLASS_OVERRIDE.get(bid, PEN_CLASS[t])
            b = b.replace('        Piercing: 0\n', '')
            if '  - type: DHBallistics\n' in b:
                b = b.replace('  - type: DHBallistics\n', f'  - type: DHBallistics\n    penetrationClass: {pc}\n')
            else:
                b = b.rstrip('\n') + f'\n  - type: DHBallistics\n    penetrationClass: {pc}\n'
            if t == 'RUB':
                b = b.rstrip('\n') + f'\n  - type: StaminaDamageOnCollide\n    damage: {RUBBER_STAMINA}\n'
        out.append(b)
    return head + ''.join(out)


def post_weapons(text):
    head, bl = blocks(text)
    out = []
    for b in bl:
        wid = re.search(r'(?m)^  id: (\S+)$', b).group(1)
        w = next(x for x in WEAPONS if x['id'] == wid)
        if w.get('bayonet'):
            b = b.rstrip('\n') + '\n' + '\n'.join(BAYONET) + '\n'
        out.append(b)
    return head + '\n'.join(x.rstrip('\n') + '\n' for x in out)


def batteries():
    out = [HEADER]
    for bid, name, shots, desc in BATTERIES:
        out.append(G.lines(
            '- type: entity', '  parent: BasePowerCell', f'  id: {bid}', f'  name: {name}', f'  description: {desc}',
            '  components:', '  - type: Sprite', '    layers:', '    - map: [ "enum.PowerCellVisualLayers.Base" ]',
            '      state: medium', '      color: "#b07a3c"', '    - map: [ "enum.PowerCellVisualLayers.Unshaded" ]',
            '      state: o2', '      shader: unshaded', '  - type: Battery', f'    maxCharge: {shots * SHOT_COST}',
            f'    startingCharge: {shots * SHOT_COST}', '  - type: Tag', '    tags:', '    - PowerCell', f'    - {bid}',
            '  - type: StaticPrice', '    price: 150') + '\n')
    return ''.join(out)


def run():
    old_cal, old_mags, old_weapons = list(G.CALIBERS), list(G.MAGS), list(G.WEAPONS)
    tmp = tempfile.mkdtemp()
    G.REPO = tmp
    G.PROTO = os.path.join(tmp, 'p')
    os.makedirs(os.path.join(G.PROTO, 'Ammunition'))
    G.HEADER = HEADER
    G.slot_whitelist = slot_whitelist
    G.CAL = {c[0]: c for c in old_cal + CALIBERS}

    G.CALIBERS = CALIBERS; G.write_ammo()
    G.MAGS = MAGS; G.write_mags()
    G.MAGS = old_mags + MAGS; G.WEAPONS = WEAPONS; G.write_weapons()

    os.makedirs(OUT, exist_ok=True)
    rd = lambda p: open(os.path.join(G.PROTO, p)).read()
    files = {
        'ammunition.yml': post_ammo(rd('Ammunition/ammunition.yml')),
        'magazines.yml': rd('Ammunition/magazines.yml'),
        'weapons.yml': post_weapons(rd('weapons.yml')),
        'batteries.yml': batteries(),
    }
    for name, text in files.items():
        open(os.path.join(OUT, name), 'w').write(text)
    tags = sorted({G.cal_tag(c[0]) for c in CALIBERS} | {m[1] for m in MAGS} | {b[0] for b in BATTERIES})
    open(TAGS, 'w').write(HEADER + ''.join(f'- type: Tag\n  id: {t}\n\n' for t in tags))
    shutil.rmtree(tmp)
    G.CALIBERS, G.MAGS, G.WEAPONS = old_cal, old_mags, old_weapons
    write_ru(files)
    print('ok', {k: v.count('- type: entity') for k, v in files.items()})


