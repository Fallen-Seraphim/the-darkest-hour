def rmc_meta(path):
    return json.load(open(os.path.join(path, 'meta.json'), encoding='utf-8-sig'))


def canvas(img, dx, width):
    out = Image.new('RGBA', (width, 32), (0, 0, 0, 0))
    out.alpha_composite(img.convert('RGBA').crop((0, 0, img.width if img.width <= width else width, 32)), (dx, 0))
    return out


def build_lav(sprite):
    src, dx, width, mount, hands, fallback, _ = LAV[sprite]
    rsi = os.path.join(RMC_GUNS, src)
    base = canvas(Image.open(os.path.join(rsi, 'base.png')).crop((0, 0, rmc_meta(rsi)['size']['x'], 32)), dx, width)
    mag = canvas(Image.open(os.path.join(rsi, 'mag-0.png')).crop((0, 0, rmc_meta(rsi)['size']['x'], 32)), dx, width)
    bolt = canvas(Image.open(os.path.join(rsi, 'bolt-open.png')).crop((0, 0, rmc_meta(rsi)['size']['x'], 32)), dx, width)
    icon = base.copy()
    icon.alpha_composite(mag)
    states = [('icon', [icon]), ('base', [base]), ('bolt-open', [bolt]), ('mag-0', [mag])]
    for kind in KINDS:
        states.append((kind, [render(stamp(kind, mount), PAL['att'], (width, 32))]))
    out = os.path.join(GUN_TEX, sprite + '.rsi')
    if os.path.isdir(out):
        shutil.rmtree(out)
    build.save_rsi(out, (width, 32), states)
    meta = json.load(open(os.path.join(out, 'meta.json')))
    meta['copyright'] = rmc_meta(rsi).get('copyright', 'RMC-14') + \
        ' | Attachment overlays drawn by Claude (Anthropic) for The Darkest Hour'
    json.dump(meta, open(os.path.join(out, 'meta.json'), 'w'), indent=2)

    # в руках, на спине и в слоте костюма
    hout = os.path.join(GUN_TEX, sprite + '_inhands.rsi')
    if os.path.isdir(hout):
        shutil.rmtree(hout)
    os.makedirs(hout)
    hmeta = {'version': 1, 'license': 'CC-BY-SA-3.0', 'copyright': '', 'size': {'x': 32, 'y': 32}, 'states': []}
    sources = set()
    for state in HAND_STATES:
        for cand in (hands, fallback):
            if not cand:
                continue
            path = os.path.join(RMC_GUNS, cand)
            st = next((s for s in rmc_meta(path)['states'] if s['name'] == state), None)
            if st:
                shutil.copyfile(os.path.join(path, state + '.png'), os.path.join(hout, state + '.png'))
                hmeta['states'].append(st)
                sources.add(rmc_meta(path).get('copyright', 'RMC-14'))
                break
    hmeta['copyright'] = '; '.join(sorted(sources))
    json.dump(hmeta, open(os.path.join(hout, 'meta.json'), 'w'), indent=2)


