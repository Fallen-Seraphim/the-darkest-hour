    meta = json.load(open(os.path.join(path, 'meta.json'), encoding='utf-8-sig'))
    have = {s['name'] for s in meta['states']}
    dummy = Mount((12, 15), (8, 24, 18), (16, 13))
    for aid, state, *_ in ATTS:
        if state in have:
            continue
        a = stamp(state, dummy)
        x0, y0, x1, y1 = a.bounds()
        a = a.moved(16 - (x0 + x1 + 1) // 2, 16 - (y0 + y1 + 1) // 2)
        render(a, PAL['att'], (32, 32)).save(os.path.join(path, state + '.png'))
        meta['states'].append({'name': state})
    json.dump(meta, open(os.path.join(path, 'meta.json'), 'w'), indent=2)


