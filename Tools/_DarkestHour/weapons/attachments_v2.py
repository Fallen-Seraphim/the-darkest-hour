def gun_info(sprite):
    """(вид, точки крепления со сдвигом DY) для любого ствола."""
    if sprite in LAV:
        return LAV[sprite][6], LAV[sprite][3]
    g = build.GUNS.get(sprite)
    if g is None:
        return None, None
    m = Mount((g.muzzle[0], g.muzzle[1] + build.DY) if g.muzzle else None,
              (g.rail[0], g.rail[1], g.rail[2] + build.DY) if g.rail else None,
              (g.under[0], g.under[1] + build.DY) if g.under else None)
    return g.kind, m


def plan_slots(sprite, kind, mount, slots, energy):
    """slots: {слот: [теги]} из прототипа. Добавляет новые слоты и расширяет списки."""
    slots = {k: list(v) for k, v in slots.items()}
    long_gun = kind in ('rifle', 'smg', 'lmg', 'sniper', 'energy')
    if OPTIC in slots:
        tags = slots[OPTIC]
        if 'DHAttachmentOptic2x' in tags and 'DHAttachmentOpticHolo' not in tags:
            tags.insert(0, 'DHAttachmentOpticHolo')
        if 'DHAttachmentOptic4x' in tags and 'DHAttachmentOptic3x' not in tags:
            tags.insert(tags.index('DHAttachmentOptic4x'), 'DHAttachmentOptic3x')
    if mount.muzzle and (long_gun or kind == 'pistol') and not energy and sprite not in NO_BARREL and BARREL not in slots:
        slots[BARREL] = ['DHAttachmentSuppressor'] if kind == 'pistol' else [GENERIC[BARREL]]
    if mount.under and GRIP not in slots and (long_gun or kind == 'autoshotgun'):
        if kind in ('lmg', 'sniper'):
            slots[GRIP] = ['DHAttachmentBipod', 'DHAttachmentHandstop']
        else:
            slots[GRIP] = ['DHAttachmentVerticalGrip', 'DHAttachmentAngledGrip', 'DHAttachmentHandstop']
    if mount.rail and OPTIC not in slots and kind == 'pistol':
        slots[OPTIC] = ['DHAttachmentOpticHolo']
    if mount.muzzle and ACC not in slots:
        slots[ACC] = [GENERIC[ACC]]
    return slots


def accepts(tags, slot, tag):
    return tag in tags or GENERIC.get(slot) in tags


def overlay_kinds(slots):
    return [k for k, (slot, tag) in KINDS.items() if slot in slots and accepts(slots[slot], slot, tag)]


def ensure_states(sprite, mount, kinds):
    """Дорисовывает в RSI ствола недостающие оверлеи (нарисованные не трогаются)."""
    path = os.path.join(GUN_TEX, sprite + '.rsi')
    meta = json.load(open(os.path.join(path, 'meta.json'), encoding='utf-8-sig'))
    have = {s['name'] for s in meta['states']}
    size = (meta['size']['x'], meta['size']['y'])
    added = 0
    for kind in kinds:
        if kind in have:
            continue
        render(stamp(kind, mount), PAL['att'], size).save(os.path.join(path, kind + '.png'))
        meta['states'].append({'name': kind})
        added += 1
    if added:
        json.dump(meta, open(os.path.join(path, 'meta.json'), 'w'), indent=2)
    return {s['name'] for s in meta['states']}


# ============================================================================ правка YAML
SLOT_RE = re.compile(r'    - name: (\S+)\n      containerId: attachment_(\w+)\n      whitelist:\n        tags:\n((?:        - \S+\n)+)')


def section_bounds(block, comp):
    i = block.find('  - type: %s\n' % comp)
    if i < 0:
        return None
    j = block.find('\n  - type: ', i + 1)
    return i, (len(block) if j < 0 else j + 1)


def drop_section(block, comp, must=None):
    b = section_bounds(block, comp)
    if b and (must is None or must in block[b[0]:b[1]]):
        block = block[:b[0]] + block[b[1]:]
    return block


def patch_block(block, stats):
    m = re.search(r'sprite: ' + re.escape(TEX) + r'/(\w+)\.rsi', block)
    if not m or m.group(1) in SKIP:
        return block
    sprite = m.group(1)
    kind, mount = gun_info(sprite)
    if kind is None or kind == 'pump':
        return block

    old = {s: [t[10:] for t in tags.strip('\n').split('\n')] for _, s, tags in SLOT_RE.findall(block)}
    slots = plan_slots(sprite, kind, mount, old, 'BatteryAmmoProvider' in block)
    if not slots:
        return block
    have = ensure_states(sprite, mount, overlay_kinds(slots))
    order = [s for s in SLOT_ORDER if s in slots]

    # слои спрайта
    block = re.sub(r'    - map: \["\w+Attachment"\]\n', '', block)
    b = section_bounds(block, 'Sprite')
    layers = ''.join('    - map: ["%s"]\n' % SLOT_LAYER.get(s, s + 'Attachment') for s in order)
    block = block[:b[1]].rstrip('\n') + '\n' + layers + block[b[1]:]

    # ItemSlots
    block = re.sub(r'      attachment_\w+:\n(?:        .*\n)+', '', block)
    b = section_bounds(block, 'ItemSlots')
    entries = ''
    for s in order:
        entries += ('      attachment_%s:\n        insertSound: /Audio/Items/screwdriver2.ogg\n'
                    '        ejectSound: /Audio/Items/screwdriver2.ogg\n        priority: 0\n        whitelist:\n'
                    '          tags:\n' % s) + ''.join('          - %s\n' % t for t in slots[s])
    block = block[:b[1]].rstrip('\n') + '\n' + entries + block[b[1]:]

    # ContainerContainer
    block = re.sub(r'      attachment_\w+: !type:ContainerSlot\n', '', block)
    block = block.replace('    containers:\n', '    containers:\n' + ''.join(
        '      attachment_%s: !type:ContainerSlot\n' % s for s in order), 1)

    # ESAttachableGun, интерфейс, ESItemMapper — заново, в конец
    block = drop_section(block, 'ESAttachableGun')
    block = drop_section(block, 'ActivatableUI', 'ESAttachableGunUiKey')
    block = drop_section(block, 'UserInterface', 'ESAttachableGunUiKey')
    block = drop_section(block, 'ESItemMapper')
    tail = ['  - type: ESAttachableGun', '    slots:']
    for s in order:
        tail += ['    - name: %s' % SLOT_NAME.get(s, 'es-gun-attachments-slot-name-' + s),
                 '      containerId: attachment_%s' % s, '      whitelist:', '        tags:']
        tail += ['        - %s' % t for t in slots[s]]
    tail += ['  - type: ActivatableUI', '    key: enum.ESAttachableGunUiKey.Key', '    verbOnly: true',
             '    verbText: es-gun-attachments-verb-text', '  - type: UserInterface', '    interfaces:',
             '      enum.ESAttachableGunUiKey.Key:', '        type: ESGunAttachmentBui', '  - type: ESItemMapper',
             '    mappings:']
    for s in order:
        maps = [(k, t) for k, (sl, t) in KINDS.items() if sl == s and k in have and accepts(slots[s], s, t)]
        if not maps:
            continue
        tail += ['      %s:' % SLOT_LAYER[s]]
        for k, t in maps:
            tail += ['      - containerId: attachment_%s' % s, '        state: %s' % k, '        whitelist:',
                     '          tags:', '          - %s' % t]
    block = block.rstrip('\n') + '\n' + '\n'.join(tail) + '\n'
    stats.append((sprite, order))
    return block


def patch_yml(path, stats):
    text = open(path, encoding='utf-8').read()
    parts = re.split(r'(?m)^(?=- type: )', text)
    body = [(patch_block(p, stats) if p.startswith('- type: entity') else p).rstrip('\n') for p in parts[1:]]
    open(path, 'w', encoding='utf-8').write(parts[0] + '\n\n'.join(body) + '\n')


