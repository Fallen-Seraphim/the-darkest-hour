def stamp(kind, g):
    if kind in ('suppressed', 'flashhider', 'compensator', 'vgrip', 'agrip', 'optic2x', 'optic4x', 'optic8x'):
        return build.stamp(kind, g)
    a = Art()
    if kind in ('muzzlebrake', 'longbarrel', 'laser', 'light'):
        mx, my = g.muzzle
        if kind == 'muzzlebrake':
            a.bevel(mx - 1, my - 1, mx + 4, my + 2, '1234', right=True)
            a.dot(mx + 1, my - 1, '0').dot(mx + 3, my - 1, '0').dot(mx + 1, my + 2, '0').dot(mx + 3, my + 2, '0')
        elif kind == 'longbarrel':
            a.bevel(mx, my, mx + 6, my + 1, '1234')
            a.vline(mx + 5, my - 1, my - 1, '2')
            a.bevel(mx + 6, my - 1, mx + 7, my + 2, '1234', right=True)
        elif kind == 'laser':
            a.bevel(mx - 9, my + 2, mx - 5, my + 3, '1234', left=True, right=True)
            a.dot(mx - 4, my + 2, 'R')
        else:
            a.bevel(mx - 10, my + 2, mx - 5, my + 4, '1234', left=True)
            a.vline(mx - 4, my + 2, my + 4, 'W')
    elif kind in ('bipod', 'handstop'):
        ux, uy = g.under
        if kind == 'bipod':
            a.hline(ux - 1, ux + 2, uy, '1')
            a.hline(ux - 8, ux + 1, uy + 1, '3').hline(ux - 8, ux + 1, uy + 2, '1')
            a.dot(ux + 2, uy + 1, '2').dot(ux - 9, uy + 2, '0')
        else:
            a.hline(ux - 1, ux + 2, uy, '1')
            a.shade_poly([(ux - 1, uy + 1), (ux + 3, uy + 1), (ux + 2, uy + 3), (ux, uy + 3)], 'abcd')
    elif kind in ('opticholo', 'optic3x'):
        x0, x1, ry = g.rail
        c = (x0 + x1) // 2
        if kind == 'opticholo':      # голографический: рамка с окном
            a.hline(c - 3, c + 3, ry - 1, '1')
            a.vline(c - 3, ry - 4, ry - 2, '2').vline(c + 3, ry - 4, ry - 2, '2')
            a.hline(c - 3, c + 3, ry - 5, '3')
            a.dot(c + 2, ry - 3, 'B').dot(c - 2, ry - 3, '0')
        else:                        # короткий 3x
            a.bevel(c - 4, ry - 3, c + 3, ry - 2, '1234')
            a.bevel(c + 3, ry - 4, c + 5, ry - 1, '1234', right=True)
            a.bevel(c - 5, ry - 4, c - 4, ry - 1, '1234', left=True)
            a.dot(c + 5, ry - 3, 'B').dot(c - 1, ry - 1, '1')
    return a


