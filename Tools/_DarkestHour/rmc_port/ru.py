def suffix(s):
    out = []
    for part in [p.strip() for p in s.split(',')]:
        if part.startswith('Damaged'):
            out.append('повреждён' + part[len('Damaged'):])
        elif part in SUF:
            out.append(SUF[part])
        elif part.isdigit() or part in ('N', 'NE', 'NW', 'SE', 'SW'):
            out.append({'N': 'С', 'NE': 'СВ', 'NW': 'СЗ', 'SE': 'ЮВ', 'SW': 'ЮЗ'}.get(part, part))
        elif part.startswith('Use East, West ['):
            out.append('ставить на восток или запад')
        else:
            raise KeyError(part)
    return ', '.join(out)
