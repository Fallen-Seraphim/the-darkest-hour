#!/usr/bin/env python3
"""Облака газового гиганта для оверлея «в слоях» (DarkestHour): белые с альфой, цвет задаёт тело.

Бесшовные (шум через FFT). Запуск из корня репозитория:
    python3 Tools/_DarkestHour/gas_giant/build.py
"""
import json
import os

import numpy as np
from PIL import Image

OUT = 'Resources/Textures/_DarkestHour/Effects/gas_layer.rsi'
rng = np.random.default_rng(6510)


def noise(size, power, stretch=(1.0, 1.0)):
    h, w = size
    fy = np.fft.fftfreq(h)[:, None] * stretch[1]
    fx = np.fft.fftfreq(w)[None, :] * stretch[0]
    f = np.sqrt(fx * fx + fy * fy)
    f[0, 0] = 1.0
    spectrum = (rng.normal(size=(h, w)) + 1j * rng.normal(size=(h, w))) / f ** power
    spectrum[0, 0] = 0
    n = np.real(np.fft.ifft2(spectrum))
    n -= n.min()
    return n / n.max()


def layer(name, size, power, stretch, cover, shade):
    """Полосы облаков, вытянутые по горизонтали, как пояса гиганта; shade — тёмные провалы между ними."""
    n = noise(size, power, stretch)
    q = np.percentile(n, 100 * (1 - cover))
    a = np.clip((n - q) / (n.max() - q), 0, 1) ** 0.8
    light = 0.55 + 0.45 * noise(size, 2.0)
    rgba = np.zeros(size + (4,))
    rgba[..., :3] = (255 * (1 - shade + shade * light))[..., None]
    rgba[..., 3] = a * 255
    Image.fromarray(rgba.astype(np.uint8)).save(os.path.join(OUT, name + '.png'), optimize=True)
    print(os.path.join(OUT, name + '.png'))


if __name__ == '__main__':
    os.makedirs(OUT, exist_ok=True)
    layer('far', (512, 512), 2.2, (2.8, 1.0), 0.75, 0.45)
    layer('near', (512, 512), 1.8, (2.0, 1.0), 0.45, 0.3)
    meta = {
        'version': 1,
        'license': 'CC-BY-SA-3.0',
        'copyright': 'DarkestHour, generated by Tools/_DarkestHour/gas_giant/build.py',
        'size': {'x': 512, 'y': 512},
        'states': [{'name': 'far'}, {'name': 'near'}],
    }
    with open(os.path.join(OUT, 'meta.json'), 'w') as f:
        json.dump(meta, f)
        f.write('\n')
