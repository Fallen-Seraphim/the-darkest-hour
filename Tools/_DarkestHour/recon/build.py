#!/usr/bin/env python3
"""Маскировочная сеть (DarkestHour): 96x96 (3x3 тайла) — сетка с лоскутами цвета пустыни, полупрозрачная;
и свёрнутая сеть 32x32. Запуск из корня репозитория:  python3 Tools/_DarkestHour/recon/build.py
"""
import json
import os

import numpy as np
from PIL import Image, ImageDraw

OUT = 'Resources/Textures/_DarkestHour/Structures/camo_net.rsi'
rng = np.random.default_rng(31)
PALETTE = [(166, 141, 96), (139, 118, 80), (190, 168, 120), (110, 96, 66), (128, 122, 84)]


def net(size=96):
    im = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    for _ in range(170):  # лоскуты
        x, y = rng.integers(2, size - 2, 2)
        w, h = rng.integers(3, 9, 2)
        c = PALETTE[rng.integers(len(PALETTE))]
        d.ellipse([x - w // 2, y - h // 2, x + w // 2, y + h // 2], fill=c + (int(rng.integers(150, 215)),))
    for i in range(0, size, 6):  # сетка
        d.line([(i, 0), (i, size - 1)], fill=(70, 60, 40, 90))
        d.line([(0, i), (size - 1, i)], fill=(70, 60, 40, 90))
    d.rectangle([0, 0, size - 1, size - 1], outline=(60, 50, 34, 140))
    return im


def folded():
    im = Image.new('RGBA', (32, 32), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    d.rounded_rectangle([5, 10, 27, 24], 4, fill=(139, 118, 80, 255), outline=(90, 76, 50, 255))
    for x in range(8, 26, 4):
        d.line([(x, 11), (x - 2, 23)], fill=(110, 96, 66, 255))
    d.line([(5, 17), (27, 17)], fill=(70, 60, 40, 255), width=2)
    return im


if __name__ == '__main__':
    os.makedirs(OUT, exist_ok=True)
    net().save(os.path.join(OUT, 'net.png'))
    folded().save(os.path.join(OUT, 'folded.png'))
    meta = {'version': 1, 'license': 'CC-BY-SA-3.0',
            'copyright': 'DarkestHour, generated by Tools/_DarkestHour/recon/build.py',
            'size': {'x': 96, 'y': 96}, 'states': [{'name': 'net'}]}
    json.dump(meta, open(os.path.join(OUT, 'meta.json'), 'w'))
    # свёрнутая — отдельный rsi 32x32
    out2 = OUT.replace('camo_net.rsi', 'camo_net_folded.rsi')
    os.makedirs(out2, exist_ok=True)
    os.replace(os.path.join(OUT, 'folded.png'), os.path.join(out2, 'icon.png'))
    json.dump(dict(meta, size={'x': 32, 'y': 32}, states=[{'name': 'icon'}]), open(os.path.join(out2, 'meta.json'), 'w'))
    print(OUT, out2)
