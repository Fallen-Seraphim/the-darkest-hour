def translit(s):
    table = {'а': 'a', 'б': 'b', 'в': 'v', 'г': 'g', 'д': 'd', 'е': 'e', 'ё': 'yo', 'ж': 'zh', 'з': 'z', 'и': 'i',
             'й': 'y', 'к': 'k', 'л': 'l', 'м': 'm', 'н': 'n', 'о': 'o', 'п': 'p', 'р': 'r', 'с': 's', 'т': 't',
             'у': 'u', 'ф': 'f', 'х': 'kh', 'ц': 'ts', 'ч': 'ch', 'ш': 'sh', 'щ': 'shch', 'ъ': '', 'ы': 'y', 'ь': '',
             'э': 'e', 'ю': 'yu', 'я': 'ya'}
    out = []
    for ch in s:
        low = ch.lower()
        t = table.get(low, ch)
        out.append(t.capitalize() if ch != low else t)
    return ''.join(out)


def feminine(last):
    """Женская форма русских фамилий (Лебедев → Лебедева, Ланской → Ланская); прочие не склоняются."""
    for end, fem in (('ский', 'ская'), ('цкий', 'цкая'), ('ской', 'ская'), ('ов', 'ова'), ('ев', 'ева'),
                     ('ёв', 'ёва'), ('ин', 'ина'), ('ын', 'ына')):
        if last.endswith(end):
            # -ин у нерусских корней (Кастильо нет, но Мартен/Северин — да): Северин — имя-фамилия, не склоняем.
            if end == 'ин' and last in NOT_DECLINED:
                return last
            return last[:-len(end)] + fem
    return last


# Фамилии на -ин, которые не склоняются (нерусские).
NOT_DECLINED = {'Северин'}


def words(text):
    seen, out = set(), []
    for w in text.split():
        if w not in seen and w not in LORE:
            seen.add(w)
            out.append(w)
    return out


def joinable(root, suffix):
    """Склеить корень и суффикс без двойных гласных/согласных на стыке."""
    vowels = 'аеёиоуыэюя'
    if root[-1] in vowels and suffix[0] in vowels:
        return None
    if root[-1] == suffix[0]:
        return None
    word = root + suffix
    if len(word) < 5 or len(word) > 12:
        return None
    return word[0].upper() + word[1:].lower()


def common_surnames(rng):
    pool = set()
    for root in LIG_ROOTS:
        for suffix in EUR_SUFFIX:
            if (w := joinable(root, suffix)):
                pool.add(w)
    for root in EUR_ROOTS:
        for suffix in LIG_SUFFIX:
            if (w := joinable(root, suffix)):
                pool.add(w)
    for root in LIG_ROOTS + EUR_ROOTS:
        for agent in AGENTS:
            if (w := joinable(root, agent)) and len(w) <= 12:
                pool.add(w)
    pool -= BAD
    pool -= LORE
    real = set(words(LAST['lig'])) | set(words(LAST['eur']))
    pool -= real
    picked = sorted(pool)
    rng.shuffle(picked)
    return sorted(picked[:240])


def main():
    rng = random.Random(2318)
    sets = {}
    for flavor in ('lig', 'eur', 'common'):
        sets['DHNamesMale' + flavor.capitalize()] = words(MALE[flavor])
        sets['DHNamesFemale' + flavor.capitalize()] = words(FEMALE[flavor])
    sets['DHNamesLastLig'] = words(LAST['lig'])
    sets['DHNamesLastEur'] = words(LAST['eur'])
    sets['DHNamesLastCommon'] = common_surnames(rng)
    # Женские формы фамилий (у русских корней: Лебедева, Ланская).
    for flavor in ('Lig', 'Eur', 'Common'):
        sets['DHNamesLastFemale' + flavor] = [feminine(w) for w in sets['DHNamesLast' + flavor]]

    # Общие наборы — для вида «Человек», NPC и бойцов: всё вместе.
    for kind in ('Male', 'Female', 'Last', 'LastFemale'):
        merged = []
        for flavor in ('Lig', 'Eur', 'Common'):
            for w in sets['DHNames%s%s' % (kind, flavor)]:
                if w not in merged:
                    merged.append(w)
        sets['DHNames' + kind] = merged

    yml = ['# Имена вселенной TDH — генерируется Tools/_DarkestHour/names/build_names.py, руками не править.', '']
    ru = ['# Имена вселенной TDH — генерируется Tools/_DarkestHour/names/build_names.py.', '',
          '# Аристократическая приставка (у уроженцев Империи, DHNameGeneratorSystem).', 'dh-name-noble = фон { $last }', '']
    en = ['# TDH names — generated by Tools/_DarkestHour/names/build_names.py.', '',
          '# Noble particle (natives of the Empire, DHNameGeneratorSystem).', 'dh-name-noble = von { $last }', '']
    for proto, values in sets.items():
        prefix = 'dh-' + ''.join('-' + c.lower() if c.isupper() else c for c in proto[2:]).lstrip('-') + '-'
        yml += ['- type: localizedDataset', '  id: %s' % proto, '  values:', '    prefix: %s' % prefix,
                '    count: %d' % len(values), '']
        for i, value in enumerate(values, 1):
            ru.append('%s%d = %s' % (prefix, i, value))
            en.append('%s%d = %s' % (prefix, i, translit(value)))
        ru.append('')
        en.append('')
        print(proto, len(values))

    open('Resources/Prototypes/_DarkestHour/Datasets/names_tdh.yml', 'w', encoding='utf-8').write('\n'.join(yml))
    open('Resources/Locale/ru-RU/_DarkestHour/names_tdh.ftl', 'w', encoding='utf-8').write('\n'.join(ru))
    open('Resources/Locale/en-US/_DarkestHour/names_tdh.ftl', 'w', encoding='utf-8').write('\n'.join(en))


if __name__ == '__main__':
    main()
