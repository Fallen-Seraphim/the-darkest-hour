#!/usr/bin/env python3
"""Текстуры разрывного пространства (DarkestHour): фон-параллакс «DHRiftSpace» и виньетка-тень оверлея.

Все слои параллакса бесшовные (шум через FFT периодичен по построению). Запуск из корня репозитория:
    python3 Tools/_DarkestHour/rift_space/build.py
"""
import os

import numpy as np
from PIL import Image

OUT = 'Resources/Textures/_DarkestHour/Parallaxes'
FX = 'Resources/Textures/_DarkestHour/Effects/rift.rsi'
rng = np.random.default_rng(2741)


def noise(size, power, stretch=(1.0, 1.0)):
    """Периодический шум со спектром 1/f^power; stretch растягивает зерно по осям (x, y)."""
    h, w = size
    fy = np.fft.fftfreq(h)[:, None] * stretch[1]
    fx = np.fft.fftfreq(w)[None, :] * stretch[0]
    f = np.sqrt(fx * fx + fy * fy)
    f[0, 0] = 1.0
    spectrum = (rng.normal(size=(h, w)) + 1j * rng.normal(size=(h, w))) / f ** power
    spectrum[0, 0] = 0
    n = np.real(np.fft.ifft2(spectrum))
    n -= n.min()
    return n / n.max()


def ramp(t, stops):
    """t 0..1 → RGB по опорным цветам [(pos, (r, g, b)), ...]."""
    pos = np.array([s[0] for s in stops])
    out = np.zeros(t.shape + (3,))
    for c in range(3):
        out[..., c] = np.interp(t, pos, [s[1][c] for s in stops])
    return out


def save(arr, path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    Image.fromarray(np.clip(arr, 0, 255).astype(np.uint8)).save(path, optimize=True)
    print(path)


def base():
    """Фиолетово-чёрная туманность: тёмная, с медленными прожилками (в прототипе растянута вдвое)."""
    size = (512, 512)
    n = noise(size, 2.3)
    veins = 1.0 - np.abs(noise(size, 1.9) * 2 - 1)  # гребни — «прожилки» разрыва
    t = np.clip(n * 0.75 + veins ** 6 * 0.45, 0, 1) ** 1.6
    rgb = ramp(t, [(0.0, (3, 1, 6)), (0.35, (12, 4, 22)), (0.6, (34, 10, 58)), (0.85, (78, 26, 112)),
                   (1.0, (150, 70, 190))])
    save(rgb, os.path.join(OUT, 'rift_base.png'))


def streaks(name, seed_shift, density, length, color, alpha_max):
    """Полосы, летящие мимо корабля: шум, вытянутый по вертикали, с порогом."""
    size = (1024, 512)
    n = noise(size, 1.0, stretch=(1.0, length))
    n2 = noise(size, 0.8, stretch=(1.0, length * 0.5))
    v = n * 0.7 + n2 * 0.3
    q = np.percentile(v, 100 * (1 - density))
    m = np.clip((v - q) / (v.max() - q), 0, 1) ** 1.4
    rgba = np.zeros(size + (4,))
    rgba[..., :3] = np.array(color)[None, None, :] * (0.6 + 0.4 * m[..., None])
    rgba[..., 3] = m * alpha_max
    save(rgba, os.path.join(OUT, name))


def vignette():
    """Тень по краям экрана для оверлея разрыва: чёрная, прозрачная к центру (цвет задаёт оверлей)."""
    s = 512
    y, x = np.mgrid[0:s, 0:s] / (s - 1) * 2 - 1
    r = np.sqrt(x * x + y * y) / np.sqrt(2)
    a = np.clip((r - 0.25) / 0.75, 0, 1) ** 1.7
    rgba = np.zeros((s, s, 4))
    rgba[..., :3] = 255
    rgba[..., 3] = a * 255
    save(rgba, os.path.join(FX, 'vignette.png'))
    meta = ('{"version":1,"license":"CC-BY-SA-3.0","copyright":"DarkestHour, generated by '
            'Tools/_DarkestHour/rift_space/build.py","size":{"x":512,"y":512},"states":[{"name":"vignette"}]}\n')
    open(os.path.join(FX, 'meta.json'), 'w').write(meta)


if __name__ == '__main__':
    base()
    streaks('rift_streaks_far.png', 1, 0.22, 10.0, (140, 70, 200), 190)
    streaks('rift_streaks_near.png', 2, 0.12, 18.0, (225, 190, 255), 235)
    vignette()
